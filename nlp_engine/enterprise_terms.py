def get_enterprise_terms(query: str) -> Optional[Dict[str, Any]]:
    """
    Looks up pre-indexed legal terms for top platforms if live crawling is blocked.
    Accepts domain strings (meesho.com), URLs (https://www.meesho.com/), or brand names (meesho).
    """
    clean = query.lower().strip()
    clean = clean.replace("https://", "").replace("http://", "").replace("www.", "").split("/")[0]
    brand = clean.split(".")[0]
    
    # Check exact domain or brand slug match
    for key, data in ENTERPRISE_TERMS_DB.items():
        if key == brand or key == clean or data.get("domain") == clean or key in clean:
            return data
            
    return None
